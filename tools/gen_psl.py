#!/usr/bin/env python3
# Test/build tool, not part of the library: turns publicsuffix.org's public_suffix_list.dat into src/tls/x509/psl.mojo.
# Usage: python3 -I tools/gen_psl.py .work/psl/psl.dat src/tls/x509/psl.mojo
# Kept: every rule with a dot, every wildcard (`*.x`) and exception (`!x.y`) rule, IDN labels as punycode, lower case.
# Dropped: single-label rules (a wildcard under any single label is refused without a list).
import sys

src, dst = sys.argv[1], sys.argv[2]
version = commit = ''
rules = set()
for line in open(src, encoding='utf-8'):
    line = line.strip()
    if line.startswith('// VERSION:'):
        version = line.split(':', 1)[1].strip()
    if line.startswith('// COMMIT:'):
        commit = line.split(':', 1)[1].strip()
    if not line or line.startswith('//'):
        continue
    line = line.split()[0].lower()
    labels = [('xn--' + l.encode('punycode').decode()) if not l.isascii() else l for l in line.split('.')]
    r = '.'.join(labels)
    if '.' in r or r.startswith('*') or r.startswith('!'):
        rules.add(r)
with open(dst, 'w') as o:
    o.write('# Public Suffix List (https://publicsuffix.org, MPL-2.0: https://mozilla.org/MPL/2.0/), generated by tools/gen_psl.py.\n')
    o.write('# VERSION %s COMMIT %s. Multi-label rules, wildcard rules and exceptions, one per line between newlines.\n' % (version, commit))
    o.write('comptime PSL = """\n' + '\n'.join(sorted(rules)) + '\n"""\n')
print('psl: %d rules, %d bytes' % (len(rules), sum(len(r) + 1 for r in rules)))
